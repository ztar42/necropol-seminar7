def download():
    """Скачивает OCR-текст, если его ещё нет; при сбое сервера пробует снова."""
    if SOURCE.exists():
        print(f"[0] Источник уже скачан: {SOURCE.name}")
        return
    print(f"[0] Скачиваю {URL} …")
    request = urllib.request.Request(URL, headers={"User-Agent": "necropol-seminar/1.0"})
    data = None
    for attempt in range(1, 5):
        try:
            with urllib.request.urlopen(request, timeout=120) as resp:
                data = resp.read()
            break
        except (urllib.error.URLError, TimeoutError) as e:
            print(f"    попытка {attempt}/4 не удалась: {e}")
            time.sleep(5 * attempt)
    if data is None:
        sys.exit("Не удалось скачать (archive.org временно недоступен). Подождите "
                 f"и запустите снова или сохраните вручную {URL} как {SOURCE}")
    text = data.decode("utf-8")
    # Контроль: это нужный текст, а не страница ошибки.
    if "Абаза, Аггей" not in text:
        sys.exit("Ошибка: в скачанном файле нет начала словаря («Абаза, Аггей»).")
    DATA.mkdir(exist_ok=True)
    SOURCE.write_text(text, encoding="utf-8")
    print(f"    готово: {len(data):,} байт")


