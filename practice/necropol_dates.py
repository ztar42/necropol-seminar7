def download():
    """Скачивает OCR-текст, если его ещё нет; при сбое сервера пробует снова."""
    if SOURCE.exists():
        print(f"[0] Источник уже скачан: {SOURCE.name}")
        return
    print(f"[0] Скачиваю {URL} …")
    request = urllib.request.Request(URL, headers={"User-Agent": "necropol-seminar/1.0"})
    data = None
    for attempt in range(1, 5):
        try:
            with urllib.request.urlopen(request, timeout=120) as resp:
                data = resp.read()
            break
        except (urllib.error.URLError, TimeoutError) as e:
            print(f"    попытка {attempt}/4 не удалась: {e}")
            time.sleep(5 * attempt)
    if data is None:
        sys.exit("Не удалось скачать (archive.org временно недоступен). Подождите "
                 f"и запустите снова или сохраните вручную {URL} как {SOURCE}")
    text = data.decode("utf-8")
    # Контроль: это нужный текст, а не страница ошибки.
    if "Абаза, Аггей" not in text:
        sys.exit("Ошибка: в скачанном файле нет начала словаря («Абаза, Аггей»).")
    DATA.mkdir(exist_ok=True)
    SOURCE.write_text(text, encoding="utf-8")
    print(f"    готово: {len(data):,} байт")


# ===========================================================================
# ЭТАП 1. Разбиение текста на статьи
# ===========================================================================

# Словарная часть начинается со статьи «Абаза, Аггей»; выше — предисловие.
START_MARKER = "Абаза, Аггей"
# Начало статьи: «Фамилия,» (с дефисами: «Гюне-фонъ»); латиница — OCR-двойники.
ENTRY_START = re.compile(r"^[А-ЯЁA-Z][а-яёъьіѣa-z]+(?:-[А-ЯЁа-яёъьіѣ]+)*,\s")
# Склеенные статьи: «…кладбище). | Бобровъ, Яковъ…» или «— см. Альштремъ. Георгъ, …»
GLUED = re.compile(
    r"(?:\)\.?|см\.\s+[^.]{2,40}\.)\s*\|?\s*"
    r"(?=[А-ЯЁ][а-яёъьі]+(?:-[А-ЯЁа-яёъьі]+)*,\s+[А-ЯЁа-яё])"
)
ALPHABET = "АБВГ"  # том 1


def is_junk(line):
    """Строка-мусор: номер страницы, колонтитул, обрывки букв."""
    s = line.strip()
    if not s:
        return False
    if re.fullmatch(r"[\dIVXLУХШ\s.,|\-—_]+", s):          # «27», «ХИ», «— 12 —»
        return True
    if len(s) > 10 and " " not in s.strip("[ ") and not re.search(r"[,.()]", s):
        return True                                          # «[о иваиасисивнвин…»
    return len(re.findall(r"[а-яё]", s)) < 3 and len(s) < 8


def split_glued(entry):
    """Режет абзац, в котором OCR слепил несколько статей подряд."""
    parts, start = [], 0
    for m in GLUED.finditer(entry):
        if entry[m.end()] == entry[0]:  # фамилия на ту же букву раздела
            parts.append(entry[start:m.end()].rstrip(" |"))
            start = m.end()
    parts.append(entry[start:])
    return [p for p in parts if p]


def segment():
    raw = SOURCE.read_text(encoding="utf-8")
    raw = raw[raw.index(START_MARKER):]

    # Абзацы по пустым строкам; убираем мусор, склеиваем строки и переносы.
    junk, texts = [], []
    for par in re.split(r"\n\s*\n", raw):
        lines = [l for l in par.split("\n") if l.strip()]
        junk += [l for l in lines if is_junk(l)]
        kept = [l for l in lines if not is_junk(l)]
        if kept:
            text = re.sub(r"(\w)- (\w)", r"\1\2", " ".join(l.strip() for l in kept))
            texts.append(re.sub(r"\s+", " ", text).strip())

    # Границы букв: раздел начинается там, где 5 кандидатов подряд на эту букву.
    cand = [i for i, t in enumerate(texts) if ENTRY_START.match(t)]
    section_start = {"А": 0}
    for letter in ALPHABET[1:]:
        for k in range(len(cand) - 4):
            if cand[k] > max(section_start.values()) and all(
                texts[cand[k + j]][0] == letter for j in range(5)
            ):
                section_start[letter] = cand[k]
                break

    def section_of(i):
        return max((s, l) for l, s in section_start.items() if s <= i)[1]

    # Новая статья — «Фамилия,» на букву своего раздела; иначе продолжение
    # предыдущей (разрыв страницы, строка эпитафии «Прохожий, чтя се…»).
    entries = []
    for i, text in enumerate(texts):
        if not entries or (ENTRY_START.match(text) and text[0] == section_of(i)):
            entries.append(text)
        else:
            entries[-1] += " " + text
    entries = [re.sub(r"(\w)- (\w)", r"\1\2", e) for e in entries]  # «де- кабря»
    entries = [part for e in entries for part in split_glued(e)]

    rows = []
    for i, e in enumerate(entries, 1):
        is_ref = bool(re.search(r"[—-]\s*см\.", e)) and len(e) < 120
        rows.append({"id": str(i), "surname": e.split(",", 1)[0],
                     "is_reference": str(int(is_ref)), "text": e})
    write_csv(OUTPUT / "entries.csv", rows, ["id", "surname", "is_reference", "text"])

    # Контроль: статьи по буквам, нарушения алфавитного порядка (первые 2 буквы).
    abc = "абвгдеёжзиійклмнопрстуфхцчшщъыьѣэюяѳ"
    key = lambda e: [abc.find(ch) for ch in e[:2].lower()]
    breaks = [(i + 1, entries[i - 1][:40], entries[i][:60])
              for i in range(1, len(entries)) if key(entries[i]) < key(entries[i - 1])]
    counts = {b: sum(1 for e in entries if e[0] == b) for b in ALPHABET}
    refs = sum(1 for r in rows if r["is_reference"] == "1")
    report = [f"Статей: {len(entries)}", f"Из них отсылок «см.»: {refs}",
              f"Выброшено строк-мусора: {len(junk)}", f"Статей по буквам: {counts}",
              f"Нарушений алфавитного порядка: {len(breaks)}", ""]
    report += [f"  #{n}: [{p}] -> [{t}]" for n, p, t in breaks[:60]]
    report += ["", "Примеры выброшенного мусора:"] + [f"  {l.strip()}" for l in junk[:40]]
    (OUTPUT / "segment_report.txt").write_text("\n".join(report) + "\n", encoding=ENC)
    print(f"[1] Статей: {len(entries)} (отсылок «см.»: {refs}); по буквам: {counts}")
    return rows


