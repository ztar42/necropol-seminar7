# ЭТАП 3. Даты рождения и смерти с механизмами контроля
# ===========================================================================

# Месяцы с учётом искажений OCR (собраны частотным подсчётом по корпусу).
I_NOISE = r"[1!|{(тпшгнШТІі'№‘]?"          # то, во что OCR превратил «і»
MONTH_PATTERNS = {
    1: r"ян\S?[ая]ря",                     # января, янзаря, янвяря
    2: r"ф?февраля",
    3: r"марта",
    4: r"апр\S{0,3}ля",                    # апрЪля, апрфля, апр$ля, апръфля
    5: r"мая",
    6: rf"{I_NOISE}[юо]{{0,2}}ня",          # юня, поня, 1юня, пюня, шоня, ня
    7: rf"{I_NOISE}[юо]{{0,2}}ля",          # юля, поля, 1юля, тюля, оля, ля
    8: r"а[вз]\S?уста",                    # августа, авлуста, азгуста
    9: r"сен\S?тября",                     # сентября, сенгября
    10: r"о[кя]\S?тября",                  # октября, окгября, оятября
    11: r"но\S?я\S?бря|нояря",             # ноября, нояабря
    12: r"дек?абря",
}
MONTH_ANY = "|".join(f"(?:{p})" for p in MONTH_PATTERNS.values())

DAY = r"[\dт|l]{1,3}(?:/\d{1,2})?"         # «т»/«|» вместо 1; «15/27» — два стиля
YEAR = r"[\dтз]{2}[\dтз.]{2}"              # «т852», «17..» (неразборчиво в издании)
YEAR_END = r"(?=[\s,.;:)]|$)"
DATE_FULL = rf"(?:({DAY})\s+)?({MONTH_ANY})\.?\s+({YEAR}){YEAR_END}"
DATE_YEAR_ONLY = rf"({YEAR}){YEAR_END}"
# До двух слов между знаком и датой: «р. въ Ригѣ 9 апрѣля», «+ убитъ 12 октября».
GAP = r"(?:(?![Ттф—\-]{1,2}\s)[^\d\s+†{|(]\S*\s+){0,2}?"
# Знак «†» в OCR: + 1 | Т т { - — ф. Не внутри слова («т» в «октября»);
# одиночная «1» — знак, только если после неё пробел («1 5 марта» = † 5 марта).
DEATH_MARK = r"(?<!\w)(?:[+†{|Ттф—\-]{1,2}(?=[\s\d])|1(?=\s))"
# «р.» — родился; «рожд.» обычно «урождённая», поэтому дата должна идти сразу.
BIRTH_MARK = rf"(?<!\w)(?:[рР]\.\s*{GAP}|рожд\.\s*)"

BIRTH_RE = re.compile(rf"{BIRTH_MARK}(?:{DATE_FULL}|{DATE_YEAR_ONLY})", re.I)
DEATH_RE = re.compile(rf"{DEATH_MARK}\s*{GAP}(?:{DATE_FULL}|{DATE_YEAR_ONLY})", re.I)
BARE_RE = re.compile(rf"(?<!\S){DATE_FULL}", re.I)  # дата без знака — запасной вариант
# Возраст только сразу после даты смерти (иначе попадается возраст внучки).
AGE_RE = re.compile(r"\s*[,;.]?\s*(?:на\s*)?(\d{1,3})\s*(?:-?м[ъь]\s*)?(?:г\.|г(?=\W)|л\.|л[ЬЪБъь]т|год)")
# Граница «своей» части статьи: скобка с местом погребения, родственники, надпись.
SCOPE_END = re.compile(
    r"(?:(?:\(|\{(?=[А-ЯЁ]))(?=[^)]{0,80}(?:кладбищ|лавр|монастыр|пустын|собор|церк|[Сс]ел[ЪЬоа]))"
    r"|\b(?:Жена|Мужъ|Мужь|Дочь|Сынъ|Дѣти|Внучка|Внукъ|Надпись)\b"
    r"|\bС[ъЪь]\s+[А-ЯЁ])"
)
YEAR_MIN, YEAR_MAX = 1700, 1912  # том издан в 1912 г.


def norm_year(s):
    """«т852» -> 1852, «1336» -> 1836 (OCR: 8 -> 3), «17..» -> None."""
    if s is None or "." in s:
        return None
    s = s.replace("т", "1").replace("з", "3")
    if not s.isdigit():
        return None
    y = int(s)
    return y + 500 if 1300 <= y < 1400 else y  # XIV века в издании нет


def norm_day(s):
    """«т»/«|» -> 1; «15/27» -> 15; «115» = знак «1» + день 15."""
    if not s:
        return None
    s = s.split("/")[0].replace("т", "1").replace("|", "1").replace("l", "1")
    if not s.isdigit():
        return None
    d = int(s)
    if d > 31 and s.startswith("1"):
        d = int(s[1:])
    return d if 1 <= d <= 31 else None


def norm_month(s):
    for num, pat in MONTH_PATTERNS.items():
        if s and re.fullmatch(pat, s, flags=re.I):
            return num
    return None


def parse(m):
    """Найденное совпадение -> (день, месяц, год)."""
    if m is None:
        return (None, None, None)
    year_only = m.group(4) if m.re.groups >= 4 else None
    if year_only:
        return (None, None, norm_year(year_only))
    return (norm_day(m.group(1)), norm_month(m.group(2)), norm_year(m.group(3)))


def iso(d):
    """(день, месяц, год) -> «ГГГГ-ММ-ДД», «ГГГГ-ММ» или «ГГГГ»."""
    day, month, year = d
    if year is None:
        return ""
    return str(year) + (f"-{month:02d}" if month else "") + (f"-{day:02d}" if month and day else "")


def extract(text):
    """Даты, возраст и флаги контроля для одной статьи."""
    body = text.split(",", 1)[1] if "," in text else text   # без фамилии
    cut = SCOPE_END.search(body)
    scope = body[:cut.start()] if cut else body             # «своя» часть

    b = BIRTH_RE.search(scope)
    birth = parse(b)
    after = scope[b.end():] if b else scope                 # смерть — после рождения
    d = DEATH_RE.search(after)
    death, source, bare = parse(d), ("mark" if d else ""), None
    if death[2] is None:
        bare = BARE_RE.search(after)
        if bare:
            death, source = parse(bare), "bare"
        if death[2] is None:
            bare = None
    a = AGE_RE.match(after[(d or bare).end():]) if (d or bare) else None
    age = int(a.group(1)) if a else None

    # Механизм контроля: флаги правдоподобия.
    flags, by, dy = [], birth[2], death[2]
    for name, y in (("birth", by), ("death", dy)):
        if y is not None and not (YEAR_MIN <= y <= YEAR_MAX):
            flags.append(f"{name}_year_out_of_range")
    if by and dy:
        calc = dy - by
        if calc < 0:
            flags.append("birth_after_death")
        elif calc > 110:
            flags.append("age_over_110")
        if age is not None and abs(calc - age) > 1:
            flags.append("age_mismatch")
    if dy is None and re.search(r"\b1[6-9]\d\d\b", scope):
        flags.append("year_present_but_no_death")
    if source == "bare":
        flags.append("death_without_mark")
    return {"birth": iso(birth), "death": iso(death), "age_stated": age,
            "age_calc": (dy - by) if (by and dy) else None,
            "flags": ";".join(flags), "scope": scope}


def extract_dates(entries):
    results = []
    for r in entries:
        res = extract(r["text"])
        res.update(id=r["id"], surname=r["surname"], is_reference=r["is_reference"])
        results.append(res)
    cols = ["id", "surname", "is_reference", "birth", "death", "age_stated", "age_calc", "flags"]
    write_csv(OUTPUT / "dates.csv", results, cols)

    # Сводка контроля.
    base = [r for r in results if r["is_reference"] == "0"]
    n = len(base)
    pct = lambda x: f"{x} ({100 * x / n:.1f}%)"
    with_age = [r for r in base if r["age_stated"] is not None and r["age_calc"] is not None]
    age_ok = sum(1 for r in with_age if "age_mismatch" not in r["flags"])
    flag_counts = Counter(f for r in base for f in r["flags"].split(";") if f)
    review = [r for r in base if r["flags"] and r["flags"] != "death_without_mark"]
    write_csv(OUTPUT / "dates_review.csv", review, cols + ["scope"])
    lines = [
        f"Статей (без отсылок «см.»): {n}",
        f"Найдена дата смерти:      {pct(sum(1 for r in base if r['death']))}",
        f"  из них полная (д-м-г):  {pct(sum(1 for r in base if len(r['death']) == 10))}",
        f"Найдена дата рождения:    {pct(sum(1 for r in base if r['birth']))}",
        f"Возраст указан и посчитан: {len(with_age)}; совпадает (±1 год): "
        f"{age_ok} ({100 * age_ok / max(len(with_age), 1):.1f}%)",
        "", "Флаги контроля:", *[f"  {k}: {v}" for k, v in flag_counts.most_common()],
        "", f"На ручную проверку (output/dates_review.csv): {len(review)}",
    ]
    (OUTPUT / "dates_report.txt").write_text("\n".join(lines) + "\n", encoding=ENC)
    print("[3] " + "\n    ".join(lines))
    return results


