import sys
import time
import urllib.error
import urllib.request
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
OUTPUT = HERE / "output"
SOURCE = DATA / "necropol_t1.txt"
URL = ("https://archive.org/download/peterburgskijnekropolt1ag60/"
       "peterburgskijnekropolt1ag60_djvu.txt")
# utf-8-sig: с этой кодировкой Excel правильно показывает кириллицу в CSV.
ENC = "utf-8-sig"


# ===========================================================================
# ЭТАП 0. Скачивание источника
