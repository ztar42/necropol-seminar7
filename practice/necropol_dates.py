def evaluate(entries, results, gold_text, title):
    """Точность и полнота по эталону. Статьи сопоставляются по началу текста."""
    starts = {r["id"]: r["text"][:45] for r in entries}
    pred = {starts[r["id"]]: r for r in results}
    gold = list(csv.DictReader(io.StringIO(gold_text.strip())))
    print(f"\n[проверка] {title}")
    for field in ("birth", "death"):
        tp = fp = fn = 0
        errors = []
        for g in gold:
            truth = g[field]
            if truth == "?":                     # значение нельзя установить
                continue
            got = pred.get(g["start"], {}).get(field, "")
            if not got and not truth:
                continue                         # верно: даты нет и не найдено
            if got == truth:
                tp += 1
            else:
                fp += bool(got)
                fn += bool(truth)
                errors.append(f"      [{g['start'][:25]}…] эталон {truth or '—'}, "
                              f"программа {got or '—'} ({g['comment']})")
        precision = tp / (tp + fp) if tp + fp else 0
        recall = tp / (tp + fn) if tp + fn else 0
        name = "рождение" if field == "birth" else "смерть"
        print(f"    {name}: верно {tp}, неверных {fp}, пропущено {fn} | "
              f"точность {precision:.0%}, полнота {recall:.0%}")
        print("\n".join(errors)) if errors else None


def write_csv(path, rows, cols):
    path.parent.mkdir(exist_ok=True)
    with path.open("w", encoding=ENC, newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def main():
    download()
    entries = segment()
    self_test()          # проверки из промтов: если код сломан, здесь будет ошибка
    results = extract_dates(entries)
    evaluate(entries, results, GOLD,
             "эталон: 60 статей (использовались при отладке, оценка завышена)")
    evaluate(entries, results, HOLDOUT,
             "отложенная выборка: 40 статей (размечены после отладки, честная оценка)")
