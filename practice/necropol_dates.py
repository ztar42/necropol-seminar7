URL = ("https://archive.org/download/peterburgskijnekropolt1ag60/"
       "peterburgskijnekropolt1ag60_djvu.txt")
# utf-8-sig: с этой кодировкой Excel правильно показывает кириллицу в CSV.
ENC = "utf-8-sig"


