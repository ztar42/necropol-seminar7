"""
Извлечение дат рождения и смерти из «Петербургского некрополя» (т. 1, 1912).
Всё решение в одном файле: скачивание источника, разбиение на статьи,
извлечение дат с механизмами контроля, проверка по ручной разметке.

Запуск (Python 3.10+, сторонние библиотеки не нужны):
    python3 necropol_dates.py

Рядом с этим файлом появятся папки:
    data/    — necropol_t1.txt, OCR-текст с archive.org (скачивается один раз)
    output/  — entries.csv (статьи), dates.csv (даты), dates_review.csv
               (статьи на ручную проверку), отчёты *_report.txt

Тот же код, разбитый на этапы, — в папке code/ (download.py, segment.py,
dates_v2.py, evaluate.py). Результаты обоих вариантов совпадают.
"""
